def number_sentences(sentences):
    return "\n".join(f"[{i}] {s}" for i, s in enumerate(sentences, 1))


def render_catalog(rows, cols, header):
    """마스터를 표로 렌더. 코드순 정렬 — 캐시 프리픽스 안정성 때문."""
    lines = [header, "| " + " | ".join(cols) + " |",
             "|" + "|".join(["---"] * len(cols)) + "|"]
    for r in sorted(rows, key=lambda x: x["code"]):
        lines.append("| " + " | ".join(str(r.get(c) or "") for c in cols) + " |")
    return "\n".join(lines)


